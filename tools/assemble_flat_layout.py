#!/usr/bin/env python3
"""Assemble the root flat layout from packs/*/ (ADR-0001 Phase 3).

``packs/<name>/`` is the single source of truth. This script derives the
compatibility flat layout that Agent Plugins / Copilot clients consume:

  com.github.copilot/agents/  <- union of every pack's resolved agents
  .github/agents/             <- same union (mirror)
  skills/                     <- union of every pack's resolved skills
  hosts/claude-code/          <- the same union, translated to a Claude
                                 Code plugin by tools/hosts/claude_code.py

Each assembled directory gets a ``.pack-generated`` marker: do not edit the
flat layout by hand -- change the pack source and re-run this script.

Usage:
  python3 tools/assemble_flat_layout.py          # regenerate the flat layout
  python3 tools/assemble_flat_layout.py --check  # CI: fail if the checked-in
                                                 # flat layout differs from
                                                 # what the packs produce

Reference resolution (same as tools/check_pack_contracts.py):
  agents:  "agents/<file>" -> packs/<name>/agents/<file>   (pack-local)
           "<file>"        -> packs/<name>/agents/<file>, then
                              packs/core/agents/<file>      (inheritance:
                              how cloud packs reuse core agents)
  skills:  "skills/<name>" -> packs/<name>/skills/<name>   (pack-local)
           "<name>"        -> skills/<name>

Two different source files mapping to the same flat name is a conflict and
fails the assembly.
"""

from __future__ import annotations

import argparse
import filecmp
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from hosts.claude_code import build_root_manifest as build_claude_root_manifest  # noqa: E402
from hosts.claude_code import build_tree as build_claude_tree  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent
PACKS_DIR = REPO_ROOT / "packs"
CORE_PACK_DIR = PACKS_DIR / "core"
TEMPLATE_DIR_NAME = "_template"

COPILOT_AGENTS = REPO_ROOT / "com.github.copilot" / "agents"
COPILOT_HOOKS = REPO_ROOT / "com.github.copilot" / "hooks"
GITHUB_AGENTS = REPO_ROOT / ".github" / "agents"
SKILLS_DIR = REPO_ROOT / "skills"
CLAUDE_TREE = REPO_ROOT / "hosts" / "claude-code"
CLAUDE_ROOT_MANIFEST = REPO_ROOT / ".claude-plugin" / "plugin.json"

MARKER_NAME = ".pack-generated"
MARKER_TEXT = (
    "Generated by tools/assemble_flat_layout.py from packs/*/.\n"
    "Do not edit -- change the pack source instead (ADR-0001).\n"
)

failures: list[str] = []


def fail(message: str) -> None:
    failures.append(message)
    print(f"FAIL: {message}")


def _rel(path: Path) -> str:
    try:
        return str(path.relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def _resolve_agent(pack_dir: Path, ref: str) -> Path | None:
    if ref.startswith("agents/"):
        candidate = pack_dir / ref
        return candidate if candidate.is_file() else None
    for base in (pack_dir / "agents", CORE_PACK_DIR / "agents"):
        candidate = base / ref
        if candidate.is_file():
            return candidate
    return None


def _resolve_skill(pack_dir: Path, ref: str) -> Path | None:
    if ref.startswith("skills/"):
        candidate = pack_dir / ref
        return candidate if candidate.is_dir() else None
    candidate = SKILLS_DIR / ref
    return candidate if candidate.is_dir() else None


def collect() -> tuple[dict[str, Path], dict[str, Path], dict[str, Path]]:
    """Return (agents, skills, hooks): flat entry name -> source path.

    Hooks are collected by directory convention — every entry of a
    pack's hooks/ directory ships — because a hook is a whole tree
    (definition, checker, rule files, vendored runtime), not a single
    manifest-referenced file like an agent or a skill.
    """
    agents: dict[str, Path] = {}
    skills: dict[str, Path] = {}
    hooks: dict[str, Path] = {}
    for pack_dir in sorted(p for p in PACKS_DIR.iterdir() if p.is_dir()):
        if pack_dir.name == TEMPLATE_DIR_NAME:
            continue
        manifest_path = pack_dir / "pack.json"
        if not manifest_path.is_file():
            fail(f"pack {pack_dir.name}/ is missing pack.json")
            continue
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        refs: list[str] = [r for r in (manifest.get("agents") or {}).values() if isinstance(r, str)]
        refs += [r for r in manifest.get("reviewers") or [] if isinstance(r, str)]
        for ref in refs:
            src = _resolve_agent(pack_dir, ref)
            if src is None:
                fail(f"{pack_dir.name}/pack.json: agent '{ref}' resolves nowhere")
                continue
            if src.name in agents and agents[src.name] != src:
                fail(
                    f"agent name conflict for '{src.name}': "
                    f"{_rel(agents[src.name])} vs {_rel(src)}"
                )
            agents[src.name] = src
        for ref in manifest.get("skills") or []:
            src = _resolve_skill(pack_dir, ref)
            if src is None:
                fail(f"{pack_dir.name}/pack.json: skill '{ref}' resolves nowhere")
                continue
            if src.name in skills and skills[src.name] != src:
                fail(
                    f"skill name conflict for '{src.name}': "
                    f"{_rel(skills[src.name])} vs {_rel(src)}"
                )
            skills[src.name] = src
        hooks_dir = pack_dir / "hooks"
        if hooks_dir.is_dir():
            for entry in sorted(hooks_dir.iterdir()):
                if entry.name in hooks and hooks[entry.name] != entry:
                    fail(
                        f"hook entry conflict for '{entry.name}': "
                        f"{_rel(hooks[entry.name])} vs {_rel(entry)}"
                    )
                hooks[entry.name] = entry
    return agents, skills, hooks


def _dir_trees_identical(left: Path, right: Path) -> bool:
    cmp = filecmp.dircmp(left, right)
    if cmp.left_only or cmp.right_only or cmp.diff_files or cmp.funny_files:
        return False
    for sub in cmp.common_dirs:
        if not _dir_trees_identical(left / sub, right / sub):
            return False
    return all(
        filecmp.cmp(left / name, right / name, shallow=False) for name in cmp.common_files
    )


def _sync_dir(dest: Path, sources: dict[str, Path]) -> None:
    """Write mode: make dest contain exactly sources + the marker file."""
    dest.mkdir(parents=True, exist_ok=True)
    wanted = set(sources) | {MARKER_NAME}
    for child in dest.iterdir():
        if child.name not in wanted:
            if child.is_dir() and not child.is_symlink():
                shutil.rmtree(child)
            else:
                child.unlink()
    for name, src in sources.items():
        target = dest / name
        if src.is_dir():
            if target.is_dir():
                shutil.rmtree(target)
            shutil.copytree(src, target)
        else:
            shutil.copy2(src, target)
    (dest / MARKER_NAME).write_text(MARKER_TEXT, encoding="utf-8")


def _check_dir(dest: Path, sources: dict[str, Path]) -> None:
    """Check mode: fail on anything the assembler would change."""
    label = _rel(dest)
    expected = set(sources) | {MARKER_NAME}
    actual = {p.name for p in dest.iterdir()} if dest.is_dir() else set()
    for name in sorted(expected - actual):
        fail(f"{label}: missing '{name}' -- run tools/assemble_flat_layout.py")
    for name in sorted(actual - expected):
        fail(f"{label}: unexpected '{name}' -- not produced from packs/*/")
    for name, src in sources.items():
        target = dest / name
        if not target.exists():
            continue
        if src.is_dir():
            if not target.is_dir() or not _dir_trees_identical(src, target):
                fail(f"{label}: '{name}' differs from pack source -- edit packs/, not the flat layout")
        elif not target.is_file() or not filecmp.cmp(src, target, shallow=False):
            fail(f"{label}: '{name}' differs from pack source -- edit packs/, not the flat layout")
    marker = dest / MARKER_NAME
    if marker.is_file() and marker.read_text(encoding="utf-8") != MARKER_TEXT:
        fail(f"{label}: marker file content changed -- it is managed by the assembler")


def _expand_tree(entries: dict[str, bytes | Path]) -> dict[str, tuple[str, object]]:
    """Flatten a generated tree to relpath -> ('bytes', bytes) | ('file', Path)."""
    files: dict[str, tuple[str, object]] = {}
    for rel, value in entries.items():
        if isinstance(value, bytes):
            files[rel] = ("bytes", value)
        else:
            for path in sorted(value.rglob("*")):
                if path.is_file():
                    files[f"{rel}/{path.relative_to(value).as_posix()}"] = ("file", path)
    files[MARKER_NAME] = ("bytes", MARKER_TEXT.encode("utf-8"))
    return files


def _sync_tree(dest_root: Path, entries: dict[str, bytes | Path]) -> None:
    """Write mode: make dest_root contain exactly the generated tree."""
    files = _expand_tree(entries)
    if dest_root.is_dir():
        for path in sorted(dest_root.rglob("*"), reverse=True):
            rel = path.relative_to(dest_root).as_posix()
            if path.is_file() and rel not in files:
                path.unlink()
            elif path.is_dir():
                try:
                    path.rmdir()
                except OSError:
                    pass
    for rel, (kind, value) in files.items():
        target = dest_root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        if kind == "bytes":
            if not (target.is_file() and target.read_bytes() == value):
                target.write_bytes(value)  # type: ignore[arg-type]
        elif not (target.is_file() and filecmp.cmp(value, target, shallow=False)):  # type: ignore[arg-type]
            shutil.copy2(value, target)  # type: ignore[arg-type]


def _check_tree(dest_root: Path, entries: dict[str, bytes | Path]) -> None:
    """Check mode: fail on anything the assembler would change."""
    files = _expand_tree(entries)
    label = _rel(dest_root)
    actual: dict[str, Path] = {}
    if dest_root.is_dir():
        for path in dest_root.rglob("*"):
            if path.is_file():
                actual[path.relative_to(dest_root).as_posix()] = path
    for rel in sorted(set(files) - set(actual)):
        fail(f"{label}: missing '{rel}' -- run tools/assemble_flat_layout.py")
    for rel in sorted(set(actual) - set(files)):
        fail(f"{label}: unexpected '{rel}' -- not produced from packs/*/")
    for rel, (kind, value) in files.items():
        target = actual.get(rel)
        if target is None:
            continue
        if kind == "bytes":
            if target.read_bytes() != value:
                fail(f"{label}: '{rel}' differs from the generated tree -- edit packs/, not hosts/")
        elif not filecmp.cmp(value, target, shallow=False):  # type: ignore[arg-type]
            fail(f"{label}: '{rel}' differs from pack source -- edit packs/, not hosts/")


def _sync_file(dest: Path, content: bytes) -> None:
    if not (dest.is_file() and dest.read_bytes() == content):
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(content)


def _check_file(dest: Path, content: bytes) -> None:
    label = _rel(dest)
    if not dest.is_file():
        fail(f"{label}: missing -- run tools/assemble_flat_layout.py")
    elif dest.read_bytes() != content:
        fail(f"{label}: differs from the generated content -- it is managed by the assembler")


def main() -> int:
    parser = argparse.ArgumentParser(description="Assemble the flat layout from packs/*/.")
    parser.add_argument("--check", action="store_true", help="fail if the flat layout is stale")
    args = parser.parse_args()

    agents, skills, hooks = collect()
    claude_entries = None
    claude_root_manifest = None
    if not failures:
        try:
            claude_entries = build_claude_tree(REPO_ROOT, PACKS_DIR, agents, skills)
            slugs = sorted(
                Path(rel).stem for rel in claude_entries if rel.startswith("agents/")
            )
            claude_root_manifest = build_claude_root_manifest(REPO_ROOT, slugs)
        except ValueError as exc:
            fail(f"claude-code target: {exc}")
    if failures:
        print(f"\n{len(failures)} assembly error(s).")
        return 1
    print(
        f"Collected {len(agents)} agents, {len(skills)} skills and "
        f"{len(hooks)} hook entries from packs/*/."
    )

    targets = [
        (COPILOT_AGENTS, agents),
        (GITHUB_AGENTS, agents),
        (SKILLS_DIR, skills),
        (COPILOT_HOOKS, hooks),
    ]
    if args.check:
        for dest, sources in targets:
            _check_dir(dest, sources)
        _check_tree(CLAUDE_TREE, claude_entries)
        _check_file(CLAUDE_ROOT_MANIFEST, claude_root_manifest)
    else:
        for dest, sources in targets:
            _sync_dir(dest, sources)
        _sync_tree(CLAUDE_TREE, claude_entries)
        _sync_file(CLAUDE_ROOT_MANIFEST, claude_root_manifest)
        print("Flat layout and Claude Code tree regenerated.")

    if failures:
        print(f"\n{len(failures)} problem(s) found.")
        return 1
    print("OK.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
